"""Runner p28 — auto-reparo: falha injetada e cobertura dos domínios.

Competitive WTA-Hebbian sobre clusters; no meio da simulação 3 dos 6
neurônios morrem. Sem glia a cobertura cai e só se recupera via
re-aprendizado lento; com glia os domínios registrados são realocados a
unidades reserva e a cobertura se mantém.

Competitive WTA-Hebbian over clusters; mid-run 3 of 6 neurons die.
Without glia coverage drops and only slowly relearns; with glia the
recorded domains are reallocated to spare units and coverage holds.
"""

import argparse

import numpy as np

from .method import recovery_steps, run

SEEDS = list(range(6))
KILLS = [1, 2, 3]


def render(res, sweep, kill_t):
    lines = [
        "# RESULTS — p28 Astromorphic self-repair",
        "",
        "Generated by `python -m papers.p28_astromorphic_repair.run --write-results`"
        " (fixed seeds, offline, numpy only). WTA-Hebbian net over 4"
        " Gaussian clusters; mid-run fault kills active neurons; glial"
        f" domain memory grafts spares. {len(SEEDS)} seeds.",
        "",
        "## Cobertura dos clusters / cluster coverage (cos do melhor vivo)",
        "",
        "| variant | pre-fault | post-fault | steps to ≥0.9 | end |",
        "|---|---|---|---|---|",
    ]
    for repair in (False, True):
        r = res[repair]
        name = "with glial repair" if repair else "no repair"
        lines.append(
            f"| {name} | {r['pre']:.3f} | {r['post']:.3f} | "
            f"{r['rec']:.0f} | {r['end']:.3f} |"
        )
    lines += [
        "",
        "## Sweep da severidade da falha / fault severity sweep",
        "",
        "| neurons killed | post-fault coverage (no repair / repair) |",
        "|---|---|",
    ]
    for nk, (c, r) in sweep.items():
        lines.append(f"| {nk}/6 | {c:.3f} / {r:.3f} |")
    lines += [
        "",
        "## Leitura / reading",
        "",
        "- Sem reparo a morte de 3/6 neurônios derruba a cobertura para"
        " ~0.6 e a rede só se recupera lentamente re-aprendendo.",
        "- Com a memória glial de domínio os reservas assumem o lugar já"
        " no domínio certo — cobertura praticamente inalterada.",
        "- Without repair killing 3/6 drops coverage to ~0.6 with slow"
        " relearning; glial domain memory grafts spares at the right"
        " domain — coverage nearly untouched.",
    ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--write-results", action="store_true")
    args = ap.parse_args()
    np.random.default_rng(args.seed)
    res = {}
    kill_t = None
    for repair in (False, True):
        H = [run(s, repair)[0] for s in SEEDS]
        H = np.array(H)
        n = H.shape[1]
        kill_t = n // 2
        res[repair] = {
            "pre": float(H[:, kill_t - 5].mean()),
            "post": float(H[:, kill_t + 1].mean()),
            "rec": float(np.mean([recovery_steps(h, kill_t) for h in H])),
            "end": float(H[:, -1].mean()),
        }
    sweep = {}
    for nk in KILLS:
        posts = []
        for repair in (False, True):
            H = np.array([run(s, repair, n_kill=nk)[0] for s in SEEDS])
            posts.append(float(H[:, H.shape[1] // 2 + 1].mean()))
        sweep[nk] = posts
    md = render(res, sweep, kill_t)
    print(md)
    if args.write_results:
        import pathlib

        out = pathlib.Path(__file__).with_name("RESULTS.md")
        out.write_text(md + "\n")
        print(f"\nwrote {out}")


if __name__ == "__main__":
    main()
